export const projectIssueArtifactContract = projectArtifactContractToIssueForm;
export const projectPullRequestArtifactContract = projectArtifactContractToPullRequestTemplate;
export const projectArtifactContractToNative = projectArtifactContractToNativeTemplate;
export const renderArtifactContractToIssueForm = renderArtifactContractIssueForm;
export const renderArtifactContractToPullRequestTemplate = renderArtifactContractPullRequestTemplate;

/** Stable path helper shared by local template sync and callers previewing output. */
export function artifactContractNativeTemplatePath(contract: Pick<ArtifactContract, "kind" | "id">): string {
  return generatedPath(contract, undefined);
}
